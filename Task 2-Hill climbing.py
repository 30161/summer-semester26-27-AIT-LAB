    visited[row][col] = True

    for dr, dc in directions:

        new_row = row + dr
        new_col = col + dc

        if (0 <= new_row < 3 and
                0 <= new_col < 3 and
                not visited[new_row][new_col]):

            find_paths(
                new_row,
                new_col,
                destination,
                path + [grid[new_row][new_col]],
                cost + 1
            )

    # Backtracking
    visited[row][col] = False


