grid = [
    ['00', '01', '02'],
    ['10', '11', '12'],
    ['20', '21', '22']
]

visited = [[False] * 3 for _ in range(3)]

directions = [
    (0, 1),    # Right
    (1, 0),    # Down
    (0, -1),   # Left
    (-1, 0)    # Up
]


def find_paths(row, col, destination, path, cost):

    # Destination reached
    if grid[row][col] == destination:
        print("Path:", " -> ".join(path))
        print("Cost:", cost)
        print()
        return

    visited[row][col] = True

    for dr, dc in directions:

        new_row = row + dr
        new_col = col + dc

        if (0 <= new_row < 3 and
                0 <= new_col < 3 and
                not visited[new_row][new_col]):

            find_paths(
                new_row,
                new_col,
                destination,
                path + [grid[new_row][new_col]],
                cost + 1
            )

    # Backtracking
    visited[row][col] = False


